#!/usr/bin/env node
// sync-extension-vocab — generate the extension-charter vocabulary module
// from the canonical JSON (single source, ADR-0040 / D11 / plan 33).
// Master: dev/scripts/sync-extension-vocab.mjs (consumer copies stay
// byte-identical — the verify-wiring vendored-script probe). Reads
// contracts/extension-charter.json NEXT TO ITSELF.
//
// Ids and shapes are GENERATED, never hand-typed: origin classes,
// categories, status states + conditions, lifecycle states, tiers,
// capability ids + tier grants, risk classes, error codes, ref
// strategies, surfaces and the verbatim consent disclosures travel from
// the charter into the TS module so UI vocabularies cannot drift.
//
// Usage:
//   node sync-extension-vocab.mjs --ts <out.ts>      write the TS module
//   node sync-extension-vocab.mjs --check <ts-path>  compare generated TS to disk (exit 1 on drift)
// Unknown "schema" versions are refused (exit 2).

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const canonicalPath = join(here, '..', 'contracts', 'extension-charter.json');

const SUPPORTED_SCHEMA = 1;
const IMPORTABLE_TIERS = new Set([0, 2]);

export function buildVocabModule(data) {
  if (data.schema !== SUPPORTED_SCHEMA || data.contract !== 'extension-charter') {
    fail(2, `unsupported contract file (schema ${data.schema}, contract ${data.contract})`);
  }

  const kindIds = Object.keys(data.kinds ?? {});
  const ladder = data.tiers?.ladder ?? [];
  const tierIds = ladder.map((t) => t.id);
  const capabilities = (data.capabilities ?? []).map((c) => ({
    id: c.id,
    tiers: c.tiers ?? [],
  }));
  const capIds = capabilities.map((c) => c.id);
  if (new Set(capIds).size !== capIds.length) fail(2, 'duplicate capability ids');
  const importable = capIds.filter((id) =>
    (capabilities.find((c) => c.id === id)?.tiers ?? []).some((t) => IMPORTABLE_TIERS.has(t)),
  );
  const disclosures = {
    t2Sandbox: data.consent?.t2SandboxDisclosure,
    t3Perimeter: data.consent?.t3PerimeterDisclosure,
    t0Declarative: data.consent?.t0DeclarativeDisclosure,
  };
  for (const [key, value] of Object.entries(disclosures)) {
    if (typeof value !== 'string' || value.length === 0) {
      fail(2, `consent disclosure ${key} missing from the charter`);
    }
  }

  const lines = [];
  const push = (s = '') => lines.push(s);
  const list = (name, value) => JSON.stringify(value);
  const asConst = (name, value) => push(`export const ${name} = ${list(name, value)} as const;`);

  push('// GENERATED by sync-extension-vocab — do not edit.');
  push('// Source: contracts/extension-charter.json (family canonical: dev/contracts/).');
  push('// Regenerate: node scripts/sync-extension-vocab.mjs --ts src/contracts/extension-charter.vocab.ts');
  push();
  asConst('EXTENSION_API_ENVELOPE', data.apiVersion?.envelope ?? 'extension/v1');
  asConst('EXTENSION_KINDS', kindIds);
  asConst('EXTENSION_ORIGIN_CLASSES', data.originClasses.vocabulary);
  asConst('EXTENSION_CATEGORIES', data.categories.vocabulary);
  asConst('EXTENSION_STATUS_STATES', data.status.states);
  asConst('EXTENSION_STATUS_CONDITIONS', data.status.conditions);
  asConst('EXTENSION_LIFECYCLE_STATES', data.lifecycle.states);
  asConst('EXTENSION_TIERS', tierIds);
  push(`export const EXTENSION_TIER_NAMES: Readonly<Record<string, string>> = {`);
  for (const t of ladder) push(`  ${JSON.stringify(t.id)}: ${JSON.stringify(t.name)},`);
  push('};');
  asConst('EXTENSION_CAPABILITIES', capIds);
  push('export const EXTENSION_CAPABILITY_TIERS: Readonly<Record<string, readonly number[]>> = {');
  for (const c of capabilities) push(`  ${JSON.stringify(c.id)}: ${JSON.stringify(c.tiers)},`);
  push('};');
  asConst('EXTENSION_IMPORTABLE_CAPABILITIES', importable);
  asConst('EXTENSION_RISK_CLASSES', data.riskClasses.vocabulary);
  asConst('EXTENSION_ERROR_CODES', (data.errors?.codes ?? []).map((e) => e.code));
  asConst('EXTENSION_RETRYABLE_VALUES', data.errors?.retryableVocabulary ?? []);
  asConst('EXTENSION_REF_STRATEGIES', data.sources?.refStrategies ?? []);
  asConst('EXTENSION_SURFACES', data.surfaces?.taxonomy ?? []);
  push(`export const EXTENSION_CONSENT_DISCLOSURES = {`);
  push(`  t2Sandbox: ${JSON.stringify(disclosures.t2Sandbox)},`);
  push(`  t3Perimeter: ${JSON.stringify(disclosures.t3Perimeter)},`);
  push(`  t0Declarative: ${JSON.stringify(disclosures.t0Declarative)},`);
  push('} as const;');
  push();
  const type = (name, from) =>
    push(`export type ${name} = (typeof ${from})[number];`);
  type('ExtensionApiEnvelope', 'EXTENSION_API_ENVELOPE');
  type('ExtensionKind', 'EXTENSION_KINDS');
  type('ExtensionOriginClass', 'EXTENSION_ORIGIN_CLASSES');
  type('ExtensionCategory', 'EXTENSION_CATEGORIES');
  type('ExtensionStatusState', 'EXTENSION_STATUS_STATES');
  type('ExtensionStatusCondition', 'EXTENSION_STATUS_CONDITIONS');
  type('ExtensionLifecycleState', 'EXTENSION_LIFECYCLE_STATES');
  type('ExtensionTier', 'EXTENSION_TIERS');
  type('ExtensionCapabilityId', 'EXTENSION_CAPABILITIES');
  type('ExtensionRiskClass', 'EXTENSION_RISK_CLASSES');
  type('ExtensionErrorCode', 'EXTENSION_ERROR_CODES');
  type('ExtensionRetryableValue', 'EXTENSION_RETRYABLE_VALUES');
  type('ExtensionRefStrategy', 'EXTENSION_REF_STRATEGIES');
  type('ExtensionSurfaceId', 'EXTENSION_SURFACES');
  push();

  return lines.join('\n');
}

function fail(code, message) {
  console.error(`sync-extension-vocab: ${message}`);
  process.exit(code);
}

const invokedDirectly =
  process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1]);
if (invokedDirectly) {
  const data = existsSync(canonicalPath)
    ? JSON.parse(readFileSync(canonicalPath, 'utf8'))
    : fail(2, `canonical file not found at ${canonicalPath}`);
  const [, , mode, target] = process.argv;
  if (mode === '--ts') {
    if (!target) fail(2, '--ts requires an output path');
    writeFileSync(target, buildVocabModule(data), 'utf8');
    console.log(`sync-extension-vocab: wrote ${target}`);
  } else if (mode === '--check') {
    if (!target) fail(2, '--check requires a path');
    if (!existsSync(target)) fail(1, `generated file missing: ${target}`);
    if (readFileSync(target, 'utf8') !== buildVocabModule(data)) {
      fail(1, `drift detected in ${target} — regenerate with: node scripts/sync-extension-vocab.mjs --ts ${target}`);
    }
    console.log('sync-extension-vocab: no drift');
  } else {
    fail(2, 'usage: sync-extension-vocab.mjs --ts <out.ts> | --check <ts-path>');
  }
}
